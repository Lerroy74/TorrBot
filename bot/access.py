"""v8: право «⬇ Качать» и «лёгкий режим».

Качать (искать раздачи, ставить закачки, подписки, «ждать качество», /status) может админ,
кто указан в ALLOWED_IDS и кому админ включил «⬇ Качать» в /users. Остальные допущенные в бот
пользуются списками, оценками и подбором — без раздач и домашнего диска.
Все, кто был в боте до v8, получили право автоматически (миграция в db_lists).
"""
from __future__ import annotations

DL = "can_dl"          # prefs: может качать
AI = "ai"              # prefs: отмечен для ИИ (если в /ai выбрано «только отмеченным»)

NO_DL = ("⬇ Качать на домашний сервер тебе не разрешено — тут доступны списки, оценки и подбор. "
         "Если нужно, попроси администратора.")


def may_download(st, uid: int) -> bool:
    cfg = st.cfg
    return uid in cfg.admin_ids or uid in cfg.allowed_ids or st.db.flag(uid, DL)
